#!/usr/bin/env python3
"""Render anti-aliased bitmap fonts (4-bit alpha) for Bob's firmware.

Usage: gen_font.py <font.ttf> <out.h>
Generates FONT_SMALL covering ASCII + German umlauts.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

CHARS = [chr(c) for c in range(32, 127)] + list("äöüÄÖÜß")
SIZES = [("FONT_SMALL", 22, 700)]


def render(ttf, name, px, weight):
    font = ImageFont.truetype(ttf, px)
    try:
        font.set_variation_by_axes([weight])
    except Exception:
        pass
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for ch in CHARS:
        l, t, r, b = font.getbbox(ch, anchor="ls")  # relative to left/baseline
        adv = round(font.getlength(ch))
        w, h = max(0, r - l), max(0, b - t)
        off = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
            px_ = list(img.get_flattened_data()) if hasattr(img, "get_flattened_data") else list(img.getdata())
            for i in range(0, len(px_), 2):
                a = px_[i] >> 4
                bb = (px_[i + 1] >> 4) if i + 1 < len(px_) else 0
                data.append((a << 4) | bb)
        glyphs.append((ord(ch), w, h, l, t, adv, off))
    out = [f"// {name}: Nunito {px}px wght {weight}, 4-bit alpha, generated by tools/gen_font.py",
           f"static const uint8_t {name}_DATA[] = {{"]
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(str(x) for x in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const BobGlyph {name}_GLYPHS[] = {{")
    for g in glyphs:
        out.append("  {%d,%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append(f"static const BobFont {name} = {{{name}_GLYPHS, {len(glyphs)}, {name}_DATA, {ascent}, {descent}}};")
    return "\n".join(out)


def main():
    ttf, dst = sys.argv[1], sys.argv[2]
    parts = ["#pragma once", "#include <stdint.h>",
             "struct BobGlyph { uint16_t cp; uint8_t w, h; int8_t xoff, yoff; uint8_t adv; uint32_t off; };",
             "struct BobFont { const BobGlyph *glyphs; uint16_t count; const uint8_t *data; uint8_t ascent, descent; };"]
    for name, px, wght in SIZES:
        parts.append(render(ttf, name, px, wght))
    open(dst, "w").write("\n\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
